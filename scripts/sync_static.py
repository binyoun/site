#!/usr/bin/env python3
"""Keep the hand-written static parts of the site in sync. Run after edits:

    python3 scripts/sync_static.py

1. Nav + footer on every /artist/<work>/ page come from scripts/partials_*.html
   (edit the partial, run this, commit).
2. The <noscript> work index on /artist/ is regenerated from data/artist.json
   so crawlers and no-JS visitors can reach every work page.
3. sitemap.xml lastmod dates come from each page's last git commit.

No build step: the output is committed plain HTML.
"""
import glob, json, re, subprocess, html
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NAV = (ROOT / 'scripts/partials_nav.html').read_text()
FOOTER = (ROOT / 'scripts/partials_footer.html').read_text()


def sync_chrome():
    n = 0
    for f in sorted(glob.glob(str(ROOT / 'artist/*/index.html'))):
        s = open(f).read()
        if '<!-- NAV -->' not in s or '<!-- FOOTER -->' not in s:
            continue
        new = s[:s.index('<!-- NAV -->')] + NAV + s[s.index('<main'):s.index('<!-- FOOTER -->')] + FOOTER
        if new != s:
            open(f, 'w').write(new)
            n += 1
    print(f'chrome: {n} page(s) updated')


def sync_noscript():
    data = json.load(open(ROOT / 'data/artist.json'))
    seen, items = set(), []
    for key in ('current', 'studio', 'installations', 'sculptures', 'lens'):
        for w in data.get(key, []):
            link, title = w.get('link'), w.get('title')
            if not link or not title or link in seen:
                continue
            seen.add(link)
            items.append(f'<li><a href="{html.escape(link)}">{html.escape(title)}</a></li>')
    block = ('<!-- NOSCRIPT-START (generated by scripts/sync_static.py) -->\n'
             '      <noscript><div class="isec"><p class="isec-l">Works</p><ul>'
             + ''.join(items) + '</ul></div></noscript>\n      <!-- NOSCRIPT-END -->')
    p = ROOT / 'artist/index.html'
    s = p.read_text()
    if 'NOSCRIPT-START' in s:
        s2 = re.sub(r'<!-- NOSCRIPT-START.*?<!-- NOSCRIPT-END -->', lambda m: block, s, flags=re.S)
    else:
        anchor = '      <div class="filter-bar"'
        s2 = s.replace(anchor, '      ' + block + '\n' + anchor, 1)
    if s2 != s:
        p.write_text(s2)
    print(f'noscript: {len(items)} works listed')


def sync_sitemap():
    p = ROOT / 'sitemap.xml'
    s = p.read_text()

    def date_for(loc):
        path = loc.replace('https://binyoun.com', '').strip('/')
        f = (path + '/' if path else '') + 'index.html'
        out = subprocess.run(['git', 'log', '-1', '--format=%cs', '--', f], cwd=ROOT,
                             capture_output=True, text=True).stdout.strip()
        return out

    def repl(m):
        loc = m.group(1)
        d = date_for(loc)
        return m.group(0) if not d else re.sub(r'<lastmod>[^<]*</lastmod>', f'<lastmod>{d}</lastmod>', m.group(0))

    s2 = re.sub(r'<url>\s*<loc>([^<]+)</loc>.*?</url>', repl, s, flags=re.S)
    if s2 != s:
        p.write_text(s2)
    print('sitemap: lastmod refreshed')


if __name__ == '__main__':
    sync_chrome()
    sync_noscript()
    sync_sitemap()
